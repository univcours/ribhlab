export const hasMaterialSymbol=name=>Object.hasOwn(MATERIAL_SYMBOLS_MAP,String(name));
export function materialSymbol(name,size=20,{filled=false,weight=500}={}){
 const key=MATERIAL_SYMBOLS_MAP[String(name)]||'description';
 const n=Number(size),dimension=Number.isFinite(n)?Math.max(12,Math.min(96,n)):20;
 const w=Number(weight),stroke=Number.isFinite(w)?Math.max(100,Math.min(700,w)):500;
 const fill=filled?1:0;
 return '<span class="material-symbols-rounded rivo-material-symbol" data-material-symbol="'+key+'" aria-hidden="true" style="font-size:'+dimension+'px;font-variation-settings:\'FILL\' '+fill+',\'wght\' '+stroke+',\'GRAD\' 0,\'opsz\' 24">'+key+'</span>';
}
